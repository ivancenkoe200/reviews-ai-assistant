# Создаем 150 строк
data = []
for i in range(150):
    base_text = random.choice(real_reviews)
    # Немного видоизменяем текст, чтобы не было полных дублей
    if i % 3 == 0:
        text = base_text + " Ужасно!"
    elif i % 3 == 1:
        text = "Пишу отзыв: " + base_text.lower()
    else:
        text = base_text.replace("Яндекс", "Сервис")
        
    source = random.choice(["irecommend", "irecommend", "google_play", "vk"])
    
    # Выбираем 1-2 случайные темы
    chosen_themes = random.sample(list(themes_pool.keys()), k=random.randint(1, 2))
    
    data.append({
        "id": i + 1,
        "date": f"2026-10-{random.randint(1, 28):02d}",
        "source": source,
        "rating": random.randint(1, 3),
        "text": text,
        "true_themes": ", ".join(chosen_themes)
    })

df = pd.DataFrame(data)

# 1. Сохраняем файл raw_reviews.csv (только id, date, source, rating, text)
df_raw = df[["id", "date", "source", "rating", "text"]]
df_raw.to_csv("raw_reviews.csv", index=False)

